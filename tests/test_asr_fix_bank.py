import pytest

from app.asr_fix import correct_asr_text


@pytest.mark.parametrize(
    "raw, fixed",
    [
        ("банк центр инвест слушаю", "банк Центр-инвест слушаю"),
        ("банк центринвест", "банк Центр-инвест"),
        ("клиент центр-инвеста", "клиент Центр-инвеста"),
        ("банк центр и вест", "банк Центр-инвест"),
        ("перевод по эс бэ пэ", "перевод по СБП"),
        ("через с б п можно", "через СБП можно"),
        ("перевела по спб вчера", "перевела по СБП вчера"),
        ("кешбек начислят", "кэшбэк начислят"),
        ("кэш бэка не было", "кэшбэка не было"),
        ("оформить ипатеку", "оформить ипотеку"),
        ("зайдите в он лайн банк", "зайдите в онлайн-банк"),
        ("в онлайн банке", "в онлайн-банке"),
        ("пин код не подходит", "ПИН-код не подходит"),
        ("подтвердите через гос услуги", "подтвердите через Госуслуги"),
        ("назовите инн", "назовите ИНН"),
    ],
)
def test_bank_terms_fixed(raw, fixed):
    assert correct_asr_text(raw) == fixed


@pytest.mark.parametrize(
    "text",
    [
        "Еду в СПб к маме",
        "встретимся в центре вечером",
        "торговый центр на западе",
        "Инна подойдёт позже",
        "кешью и бекон",
        "Ипатьевский переулок",
        "центр вестибюля",
    ],
)
def test_normal_words_untouched(text):
    assert correct_asr_text(text) == text
