# Слова, которые чаще значат не имя: «Слава богу», «Роза ветров» и т. п.
AMBIGUOUS = {"слава", "роза", "майя", "ника", "лев", "ева", "мила", "кира", "зоя", "яна", "любовь", "вера", "надежда", "марк"}

_HUSH = set("гкхжшчщ")


def _yo(word: str) -> str:
    return word.lower().replace("ё", "е")


def _forms(name: str) -> set[str]:
    w = _yo(name)
    out = {w}
    if w.endswith(("ий", "ей", "ай")):
        s, v = w[:-1], w[-2]
        out |= {s + "я", s + "ю", s + "ем", s + "е", s + "и"}
        if v == "и":
            out |= {s + "ем"}
    elif w.endswith("ия"):
        s = w[:-1]
        out |= {s + "и", s + "ю", s + "ей"}
    elif w.endswith("я"):
        s = w[:-1]
        out |= {s + "и", s + "е", s + "ю", s + "ей", s + "ей"}
    elif w.endswith("а"):
        s = w[:-1]
        gen = s + ("и" if s[-1] in _HUSH else "ы")
        ins = s + ("ей" if s[-1] in "жшчщц" else "ой")
        out |= {gen, s + "е", s + "у", ins}
    elif w.endswith("ь"):
        s = w[:-1]
        out |= {s + "я", s + "ю", s + "ем", s + "е", s + "и"}
    else:
        # согласная: Иван, Олег; беглая «е»: Павел - Павла, Лев - Льва
        stems = {w}
        if w == "павел":
            stems = {"павл"}
        elif w == "лев":
            stems = {"льв"}
        for s in stems:
            out |= {s + "а", s + "у", s + "ом", s + "е"}
    return out


@lru_cache(maxsize=1)
def name_forms() -> frozenset[str]:
    forms: set[str] = set()
    for name in (MALE + " " + FEMALE).split():
        forms |= _forms(name)
    return frozenset(forms)


_WORD = re.compile(r"(?<![А-ЯЁа-яё\-])[А-ЯЁ][а-яё]+(?![А-ЯЁа-яё])")


def is_first_name(word: str, strict: bool = False) -> bool:
    """Слово с заглавной буквы - известное имя. strict=True пропускает многозначные (Вера, Слава)."""
    if not word or not word[0].isupper():
        return False
    w = _yo(word)
    if w not in name_forms():
        return False
    if strict and w in {_yo(a) for a in AMBIGUOUS}:
        return False
    return True


def find_first_names(text: str, strict: bool = False) -> list[re.Match]:
    return [m for m in _WORD.finditer(text or "") if is_first_name(m.group(0), strict)]
