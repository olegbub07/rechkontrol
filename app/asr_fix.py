from __future__ import annotations

import re

# Типичные ошибки Whisper base на русской банковской речи.
# Только правила с банковским контекстом: каждое срабатывает на фразе, которая
# вне банковского разговора почти не встречается. Одиночные обычные слова
# («щита», «грипп», «являете с») глобально не заменяются: это портит нормальный текст.
# Порядок важен: сначала длинные устойчивые фразы.
_REPLACEMENTS: tuple[tuple[str, str], ...] = (
    (r"(?i)\bцентр(?:[\s\-]*ин|[\s\-]+и|[\s\-]*ен)[\s\-]*вест?(а|е|у|ом)?\b", r"Центр-инвест\1"),
    (r"(?i)\bцентринвест(а|е|у|ом)?\b", r"Центр-инвест\1"),
    (r"(?i)\bцентренвест(а|е|у|ом)?\b", r"Центр-инвест\1"),
    (r"(?i)\bcentr[\s\-]*invest\b", "Центр-инвест"),
    (r"(?i)(Центр-инвест)[\s\-]+(?:онлайн|online)\b", r"\1 Онлайн"),
    (r"(?i)\bбизнес[\s\-]+(?:онлайн|online)\b", "Бизнес Онлайн"),
    # карты: Mir Supreme / Mir Supreme+, UnionPay
    (r"(?i)\bмир[\s\-]+с[уюy]пр[иеэ]м(?:[\s\-]*(?:\+|плюс\b))?", lambda m: "Mir Supreme+" if ("+" in m.group(0) or "плюс" in m.group(0).lower()) else "Mir Supreme"),
    (r"(?i)\bюнион[\s\-]*п[еэ]й\b", "UnionPay"),
    # вклады банка: «вклад универсальный» -> «вклад «Универсальный»»
    (r"(?i)\b(вклад\w*)\s+«?(универсальн|премиальн|эксклюзивн|сезонн)(\w*)»?", lambda m: f"{m.group(1)} «{m.group(2).capitalize()}{m.group(3)}»"),
    (r"(?i)\bэкв[аоы]й?[еэи]?ринг(\w*)", r"эквайринг\1"),
    (r"(?i)\bснилс(а|у|ом|е)?\b", r"СНИЛС\1"),
    (r"(?i)\bфин[\s\-]+услуг(\w*)", r"Финуслуг\1"),
    # СБП: «эс бэ пэ», «эсбэпэ», «с б п»; «по СПБ» в контексте перевода
    (r"(?i)\bэс[\s\-]*бэ[\s\-]*пэ\b", "СБП"),
    (r"(?i)(?<![\w\-])с\s+б\s+п(?![\w\-])", "СБП"),
    (r"(?i)\bсбп\b", "СБП"),
    (r"(?i)\b(перев\w*(?:\s+\S+){0,3}?\s+(?:по|через))\s+спб\b", r"\1 СБП"),
    (r"(?i)\bсистем(\w*)\s+быстрых\s+плат[её]ж", r"систем\1 быстрых платеж"),
    # кэшбэк в любом написании
    (r"(?i)\bк[еэ]ш[\s\-]*б[еэ]к(\w*)", r"кэшбэк\1"),
    (r"(?i)\bипат[еэ]к(\w*)", r"ипотек\1"),
    (r"(?i)\bипот[э]к(\w*)", r"ипотек\1"),
    (r"(?i)\bон[\s\-]*лайн[\s\-]*банк(\w*)", r"онлайн-банк\1"),
    (r"(?i)\bовер[\s\-]+драфт(\w*)", r"овердрафт\1"),
    (r"(?i)\bпин[\s\-]*код(\w*)", r"ПИН-код\1"),
    (r"(?i)\bгос[\s\-]+услуг(\w*)", r"Госуслуг\1"),
    (r"(?i)\bинн\b", "ИНН"),
    (r"(?i)\bбик\b", "БИК"),
    (r"(?i)\bявляете с клиентом\b", "являетесь клиентом"),
    (r"(?i)\bна\s+логобложен", "налогообложен"),
    (r"(?i)\bупрошенк", "упрощёнк"),
    (r"(?i)\bупрощенк", "упрощёнк"),
    (r"(?i)\bпаспорт\s+иный\s+лист\s+запис[ьие]?\b", "паспорт, ИНН и лист записи"),
    (r"(?i)\bпаспорт\s+и\s+нелист\s+запис[ьие]?\b", "паспорт, ИНН и лист записи"),
    (r"(?i)\bи\s+нелист\s+запис[ьие]?\b", "ИНН и лист записи"),
    (r"(?i)\bнелист\s+запис[ьие]?\b", "ИНН и лист записи"),
    (r"(?i)\bиный\s+лист\s+запис[ьие]?\b", "ИНН и лист записи"),
    (r"(?i)(лист\w*\s+записи)\s+и\s+грипп?\b", r"\1 и ЕГРИП"),
    (r"(?i)\b(выписк\w*\s+из)\s+(?:и\s+)?грипп?\b", r"\1 ЕГРИП"),
    (r"(?i)\bегрипп?\b", "ЕГРИП"),
    (r"(?i)\bдля открытия щита\b", "для открытия счёта"),
    (r"(?i)\bоткрытия щита\b", "открытия счёта"),
    (r"(?i)\b[щч][её]т откроем\b", "счёт откроем"),
    (r"(?i)\bрасчетн", "расчётн"),
    # «Чем могу помочь?» слитно: «Чемогом помочь», «Чемогу помочь»
    (r"\b([Чч])ем[оа]?г[оу]м?\s+помочь", r"\1ем могу помочь"),
)

_COMPILED = [(re.compile(pat), repl) for pat, repl in _REPLACEMENTS]


def correct_asr_text(text: str) -> str:
    if not text:
        return text
    out = text
    for pattern, repl in _COMPILED:
        out = pattern.sub(repl, out)
    return re.sub(r"\s{2,}", " ", out).strip()


def correct_segments(segments: list[dict]) -> list[dict]:
    fixed: list[dict] = []
    for seg in segments:
        item = dict(seg)
        item["text"] = correct_asr_text(seg.get("text") or "")
        if item["text"]:
            fixed.append(item)
    return fixed
